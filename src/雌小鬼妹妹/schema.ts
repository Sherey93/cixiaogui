// 雌小鬼妹妹 · MVU 变量结构（Zod 4）
// 事实来源：创作规划.yaml 的 mvu 段（structure + variables），字段名与枚举值逐字一致
// 硬约定：
//   1. 顶部不写任何导入语句 —— z 与 _ 由 MVU 运行时注入；
//   2. 六块顶层字段全部必填，每格都给 .prefault 初值，对象再补 .prefault({})，
//      这样局部 JSON Patch 或整块 remove 之后仍能解析回完整结构；
//   3. 0~100 的数值用 _.clamp 夹回范围（不报错、不丢弃更新），不另加规划没写的限制。
// 叶子变量总数：21（世界 4 / 妈妈 5 / 妹妹 4 / 操盘 5 / 风险 2 / 小雨 1）
// 规划已明确：妈妈对肛交的过程不设变量，故此处无对应字段。

export const Schema = z.object({
  // ─────────────── 世界 ───────────────
  世界: z
    .object({
      日期: z
        .string()
        .describe('当前日期，格式必须是 YYYY/MM/DD；跨过午夜时加一天，并同步 世界.星期')
        .prefault('2026/11/27'),
      时刻: z
        .string()
        .describe(
          '当前具体时刻，格式必须是 24 小时制 HH:MM；按时间结构走（16:30–20:15 只有兄妹，20:15–23:00 三个人，23:00 之后各自回房），不许一轮之内跳到第二天',
        )
        .prefault('21:10'),
      星期: z
        .enum(['一', '二', '三', '四', '五', '六', '日'])
        .describe('星期几，取值是一到日；周末美容院最忙，妈妈回家最晚')
        .prefault('五'),
      场景: z
        .enum([
          '客厅',
          '妈妈的房间',
          '妹妹的房间',
          '哥哥的房间',
          '走廊',
          '卫生间',
          '楼道',
          '小区与街上',
          '美容院',
          '外面',
        ])
        .describe(
          '<user>当前所在的位置，决定地理条目是否被激活；餐厅、厨房、玄关都算客厅这一片，校门口、便利店、小区里都算小区与街上，同一场景里连续发生的事不反复改值',
        )
        .prefault('客厅'),
    })
    .prefault({}),

  // ─────────────── 妈妈 ───────────────
  // 全卡第二主线。她的四个阶段是她自己一步步迈出去的，不是被推过去的
  妈妈: z
    .object({
      位置: z
        .enum(['在美容院', '在回家路上', '刚进门', '客厅', '卫生间', '她的房间'])
        .describe(
          '妈妈的物理位置，全卡节拍器的第一格；她只在店和家两个地方，中间这段「在回家路上」是最紧的窗口',
        )
        .prefault('在美容院'),
      状态: z
        .enum(['平常', '卸妆', '洗完澡', '微醺', '累', '睡着了'])
        .describe(
          '妈妈此刻的样子，决定她看见什么、漏掉什么；她还没回来时不必更新。「卸妆」是最不设防的十分钟，「微醺」时防线松动但人仍然清醒',
        )
        .prefault('平常'),
      妈妈线: z
        .enum(['无防备', '动摇', '默许', '越线'])
        .describe(
          '妈妈这条线的四格阶梯，只能一格一格往上不许跳；主触发是玩家和她之间的一次实质突破，妹妹的推力只是把门槛降下来的催化剂',
        )
        .prefault('无防备'),
      对女儿信任: z.coerce
        .number()
        .describe(
          '她把女儿当贴心小棉袄的程度，0~100；说心事、帮着分担时涨，察觉被女儿算计（风险.妈妈起疑 高于 60 之后）会掉 10~20。这一项越高，妹妹的手法越好使',
        )
        .prefault(75)
        .transform((值) => _.clamp(值, 0, 100)),
      感情深度: z.coerce
        .number()
        .describe(
          '她心里把他放哪儿，0~100，和「妈妈线」是两条轴不互相代用；非性的亲密（被照顾、被依赖、产生独占感）才涨，只有性行为不涨，被明确拒绝或冷落会掉',
        )
        .prefault(20)
        .transform((值) => _.clamp(值, 0, 100)),
    })
    .prefault({}),

  // ─────────────── 妹妹 ───────────────
  // 全卡第一推动者。她不是在牺牲，她是在进攻
  妹妹: z
    .object({
      阶段: z
        .enum(['试探', '加码', '要账', '三个人'])
        .describe(
          '全卡第一主线刻度，决定她当天在做什么、敢要什么；只能被玩家行为推动，AI 不得自己跳阶段。走到「要账」有主路径（妈妈已越线）和逆转路径（报酬阶梯到陪我睡、妈妈线还停在无防备或动摇）两条',
        )
        .prefault('试探'),
      报酬阶梯: z
        .enum(['摸头', '抱一下', '亲脸', '亲嘴', '陪我睡', '要我'])
        .describe(
          '她已经开到哪一级，全卡最核心的一条刻度；每一级都是她自己开口要来的，玩家付过一次才能往上抬一级，不许连跳，玩家赖账时不降级但她下次要得更多',
        )
        .prefault('摸头'),
      醋劲: z.coerce
        .number()
        .describe(
          '她吃醋的程度，0~100；看到哥哥和妈妈亲近、哥哥碰别的女人、自己被冷落会涨，被单独哄或被付报酬会降。31 以上开始当场插话，61 以上故意拆自己的局，86 以上公开地酸——但无论多高她都不承认在吃醋',
        )
        .prefault(10)
        .transform((值) => _.clamp(值, 0, 100)),
      在场: z
        .boolean()
        .describe('她此刻是否在<user>能看见的范围内；场景切到美容院、学校、外面时通常为 false，在家里通常为 true')
        .prefault(true),
    })
    .prefault({}),

  // ─────────────── 操盘 ───────────────
  // 五个推力开关。只记「这一手有没有用成过」，不记进度条
  操盘: z
    .object({
      破防衣着: z
        .boolean()
        .describe(
          '手法一「破防衣着防线」有没有用成过；睡裙塞进妈妈衣柜或直接塞到她手里、而且她真的换上并穿着在客厅走动过才置 true，之后不回落',
        )
        .prefault(false),
      消除羞耻: z
        .boolean()
        .describe(
          '手法二「消除妈妈的道德羞耻感」有没有用成过；当着妈妈的面把年下恋、成熟姐姐更抢手这类话聊开，妈妈接住了话头顺着说且没骂她胡说就置 true',
        )
        .prefault(false),
      接触共处: z
        .boolean()
        .describe(
          '手法三「制造合法身体接触与共处空间」有没有用成过；按摩（把人按到妈妈身边）或酒局（果酒灌到微醺、自己溜回房、把灯关暗）任一种做成即置 true，之后成为常规操作',
        )
        .prefault(false),
      危机吃醋: z
        .boolean()
        .describe(
          '手法四「精准制造危机与吃醋」有没有用成过；在妈妈面前放出「哥最近好像有女生在追」这类话、妈妈真的开始管他，即置 true',
        )
        .prefault(false),
      把风掩护: z
        .boolean()
        .describe(
          '手法五「终极掩护与共谋把风」有没有用成过；替哥哥和妈妈腾过房间、或在客厅挡过走廊视线、把音量调大盖过声音，即置 true，之后变成三个人之间的默契',
        )
        .prefault(false),
    })
    .prefault({}),

  // ─────────────── 风险 ───────────────
  // 两条各自独立，不许合并成一个数字；「哥哥看穿」那一层不设变量，归玩家自己掌握
  风险: z
    .object({
      外人察觉: z.coerce
        .number()
        .describe(
          '外面的人（王姨、周姐、陈可、店里的人、学校）知道这家里的事到了什么程度，0~100；超过 30 王姨开始多看两眼，超过 55 周姐开始问，超过 80 会有具体传言回到这家人耳朵里',
        )
        .prefault(10)
        .transform((值) => _.clamp(值, 0, 100)),
      妈妈起疑: z.coerce
        .number()
        .describe(
          '妈妈发现「女儿在操盘」的程度，0~100，和「妈妈被攻略」方向相反、不互相代用；超过 40 她开始留意女儿的话，超过 65 会当面问一句，超过 85 她会明白过来（那时妹妹阶段和妈妈线都必须已经走完）',
        )
        .prefault(5)
        .transform((值) => _.clamp(值, 0, 100)),
    })
    .prefault({}),

  // ─────────────── 小雨 ───────────────
  // 次要角色，只活在美容院这个空间里，不进状态栏
  小雨: z
    .object({
      亲近度: z.coerce
        .number()
        .describe(
          '美容院店员小雨对<user>的亲近程度，0~100；去店里帮忙、带东西、多说话才涨，只活在美容院，不推进妹妹线和妈妈线。超过 50 她会主动找话说，超过 75 她会等他来，上限只到「店里那点暧昧」',
        )
        .prefault(0)
        .transform((值) => _.clamp(值, 0, 100)),
    })
    .prefault({}),
}).prefault({});

export type Schema = z.output<typeof Schema>;
